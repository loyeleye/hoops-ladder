// Copies the Hoops Ladder web prototype into www/ and adapts it to run offline inside the Android app.
// Usage: node tools/import_prototype.mjs <prototype-folder>
// The prototype folder holds index.html, vision_bundle.mjs, wasm/, animations/*.gif and pose_lite.b64.txt.
// Run it again whenever the prototype changes; it rebuilds www/ from scratch. See docs/LEARNING.md, step 2.
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src || !fs.existsSync(path.join(src, "index.html"))) {
  console.error("Usage: node tools/import_prototype.mjs <prototype-folder>");
  process.exit(1);
}
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const www = path.join(root, "www");
fs.rmSync(www, { recursive: true, force: true });
for (const d of ["", "anim", "wasm", "fonts"]) fs.mkdirSync(path.join(www, d), { recursive: true });

// 1. Copy the MediaPipe bundle and its WebAssembly files as they are.
fs.copyFileSync(path.join(src, "vision_bundle.mjs"), path.join(www, "vision_bundle.mjs"));
for (const f of fs.readdirSync(path.join(src, "wasm"))) fs.copyFileSync(path.join(src, "wasm", f), path.join(www, "wasm", f));

// 2. Copy only the step GIFs the page actually references (it loads them from anim/).
let html = fs.readFileSync(path.join(src, "index.html"), "utf8");
const gifs = [...new Set(html.match(/[a-z0-9_]+\.gif/g) || [])];
for (const g of gifs) {
  const from = path.join(src, "animations", g);
  if (fs.existsSync(from)) fs.copyFileSync(from, path.join(www, "anim", g));
  else console.warn("missing GIF:", g);
}

// 3. The pose model was stored as base64 text so a Claude-hosted page could fetch it. Decode it back to the binary .task file.
const b64 = fs.readFileSync(path.join(src, "pose_lite.b64.txt"), "utf8").trim();
fs.writeFileSync(path.join(www, "pose_landmarker_lite.task"), Buffer.from(b64, "base64"));

// 4. Bundle the fonts (SIL Open Font License) so the app needs no network.
const fonts = { "Saira Condensed": ["saira-condensed", [500, 600, 700, 800]], Barlow: ["barlow", [400, 500, 600, 700]] };
let css = "/* Generated by tools/import_prototype.mjs from @fontsource packages (SIL OFL 1.1). */\n";
for (const [family, [pkg, weights]] of Object.entries(fonts)) {
  for (const w of weights) {
    const file = `${pkg}-latin-${w}-normal.woff2`;
    fs.copyFileSync(path.join(root, "node_modules/@fontsource", pkg, "files", file), path.join(www, "fonts", file));
    css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${w};font-display:swap;src:url(${file}) format("woff2")}\n`;
  }
}
fs.writeFileSync(path.join(www, "fonts", "fonts.css"), css);

// 5. Patch the page. Each patch must match exactly once, so a changed prototype fails loudly instead of silently.
function patch(name, from, to) {
  const n = html.split(from).length - 1;
  if (n !== 1) throw new Error(`patch "${name}" matched ${n} times; update tools/import_prototype.mjs`);
  html = html.replace(from, to);
}
// Claude pages add the document skeleton when they publish; a real app page needs its own.
// viewport-fit=cover lets the page draw under the status bar; the CSS already pads with env(safe-area-inset-*).
patch("claude meta", '<meta name="claude:viewport-fit-sides" content="cover">\n', "");
patch(
  "google fonts",
  '<link rel="preconnect" href="https://fonts.googleapis.com">\n<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Saira+Condensed:wght@500;600;700;800&family=Barlow:wght@400;500;600;700&display=swap">',
  '<link rel="stylesheet" href="fonts/fonts.css">'
);
patch(
  "pose model",
  'const b64=await (await fetch(new URL("pose_lite.b64.txt",base).href)).text();const bin=atob(b64.trim()),buf=new Uint8Array(bin.length);for(let i=0;i<bin.length;i++)buf[i]=bin.charCodeAt(i);',
  'const buf=new Uint8Array(await (await fetch(new URL("pose_landmarker_lite.task",base).href)).arrayBuffer());'
);
// App-only page code (native-web/native.js): progress storage, volume-button and lock-screen logging.
// The page's whole app lives inside one (()=>{ ... })(); so its names (S, R, persist, openBig, ...) are private.
// native.js goes in just before that closing })(); so it can see and wrap those functions. See docs/LEARNING.md, step 8.
{
  const end = html.lastIndexOf("})();\n</script>");
  if (end < 0 || html.indexOf("</script>", end + 6) !== html.lastIndexOf("</script>"))
    throw new Error('native.js: the page no longer ends with "})();</script>"; update tools/import_prototype.mjs');
  const code = fs.readFileSync(path.join(root, "native-web", "native.js"), "utf8");
  html = html.slice(0, end) + "\n/* ---- native-web/native.js (added by tools/import_prototype.mjs) ---- */\n" + code + "\n" + html.slice(end);
}
html =
  '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' +
  html.replace(/<\/style>/, "</style>\n</head>\n<body>") +
  "\n</body>\n</html>\n";
fs.writeFileSync(path.join(www, "index.html"), html);
console.log(`www/ rebuilt: ${gifs.length} GIFs, model ${(fs.statSync(path.join(www, "pose_landmarker_lite.task")).size / 1e6).toFixed(1)} MB`);
